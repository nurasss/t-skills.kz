const traitByName: Record<string, string> = Object.fromEntries(
  T_SKILLS_WORKING_TAXONOMY.map((trait) => [trait.name, trait.id]),
);

function item(
  number: number,
  leftText: string,
  rightText: string,
  leftTraitName: string,
  rightTraitName: string,
): PairwiseItem {
  const leftTraitId = traitByName[leftTraitName];
  const rightTraitId = traitByName[rightTraitName];
  if (!leftTraitId || !rightTraitId) throw new Error(`Unknown T-Skills trait in item ${number}`);
  return {
    id: `TS${String(number).padStart(3, "0")}`,
    leftTraitId,
    rightTraitId,
    leftText,
    rightText,
    version: T_SKILLS_VERSION_IDS.itemBank,
  };
}

