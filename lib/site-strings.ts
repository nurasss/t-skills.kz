/**
 * Статусы автосохранения/сессии, видимые во время прохождения теста.
 * При переключении языка отображения уже показанный статус переводится
 * на новый язык без перезапуска теста и без повторной записи ответов:
 * значение совпало со строкой старого языка — вернуть строку нового.
 * Неизвестные строки возвращаются как есть. Язык версионированной сессии
 * (сервер, только ru) это не затрагивает — только display-текст.
 */
const TRANSLATABLE_STATUS_KEYS = [
  "ready",
  "saved",
  "offline",
  "scoring",
  "saving",
  "creatingSession",
  "sessionReady",
] as const;

export function translateControllerStatus(current: string, from: "ru" | "kk", to: "ru" | "kk"): string {
  if (from === to) return current;
  for (const key of TRANSLATABLE_STATUS_KEYS) {
    if (current === CTRL_STRINGS[from][key]) return CTRL_STRINGS[to][key];
  }
  return current;
}

