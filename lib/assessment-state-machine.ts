export const SESSION_STATES = [
  "CREATED",
  "PAYMENT_PENDING",
  "PAID",
  "ENTITLED",
  "CONSENTED",
  "CORE_IN_PROGRESS",
  "CORE_COMPLETE",
  "ADAPTIVE_GENERATING",
  "ADAPTIVE_SELECTING",
  "ADAPTIVE_IN_PROGRESS",
  "ADAPTIVE_PROVIDER_FAILED",
  "ADAPTIVE_FALLBACK",
  "SCORING",
  "REPORT_GENERATING",
  "COMPLETE",
  "PAYMENT_FAILED",
  "EXPIRED",
  "CANCELLED",
  "INVALIDATED",
  "REPORT_FAILED_RETRYABLE",
] as const;

export type SessionState = (typeof SESSION_STATES)[number];

const ALLOWED_TRANSITIONS: Readonly<Record<SessionState, readonly SessionState[]>> = {
  CREATED: ["PAYMENT_PENDING", "PAID", "ENTITLED", "CANCELLED", "EXPIRED"],
  PAYMENT_PENDING: ["PAID", "PAYMENT_FAILED", "CANCELLED", "EXPIRED"],
  PAID: ["CONSENTED", "CANCELLED", "EXPIRED"],
  ENTITLED: ["CONSENTED", "CANCELLED", "EXPIRED"],
  CONSENTED: ["CORE_IN_PROGRESS", "CANCELLED", "INVALIDATED"],
  CORE_IN_PROGRESS: ["CORE_IN_PROGRESS", "CORE_COMPLETE", "ADAPTIVE_SELECTING", "ADAPTIVE_IN_PROGRESS", "INVALIDATED"],
  CORE_COMPLETE: ["ADAPTIVE_GENERATING", "ADAPTIVE_SELECTING", "ADAPTIVE_IN_PROGRESS", "INVALIDATED"],
  ADAPTIVE_GENERATING: ["ADAPTIVE_IN_PROGRESS", "ADAPTIVE_PROVIDER_FAILED", "ADAPTIVE_FALLBACK", "INVALIDATED"],
  ADAPTIVE_SELECTING: ["ADAPTIVE_IN_PROGRESS", "INVALIDATED"],
  ADAPTIVE_PROVIDER_FAILED: ["ADAPTIVE_GENERATING", "ADAPTIVE_FALLBACK", "ADAPTIVE_IN_PROGRESS", "INVALIDATED"],
  ADAPTIVE_FALLBACK: ["ADAPTIVE_IN_PROGRESS", "SCORING", "REPORT_GENERATING", "INVALIDATED"],
  ADAPTIVE_IN_PROGRESS: ["ADAPTIVE_IN_PROGRESS", "SCORING", "REPORT_GENERATING", "INVALIDATED"],
  SCORING: ["REPORT_GENERATING", "REPORT_FAILED_RETRYABLE", "INVALIDATED"],
  REPORT_GENERATING: ["COMPLETE", "REPORT_FAILED_RETRYABLE", "INVALIDATED"],
  REPORT_FAILED_RETRYABLE: ["REPORT_GENERATING", "COMPLETE", "INVALIDATED"],
  COMPLETE: ["INVALIDATED"],
  PAYMENT_FAILED: ["PAYMENT_PENDING", "PAID", "CANCELLED", "EXPIRED"],
  EXPIRED: [],
  CANCELLED: [],
  INVALIDATED: [],
};

export function canSessionTransition(from: SessionState, to: SessionState) {
  return from === to || ALLOWED_TRANSITIONS[from].includes(to);
}

export function assertSessionTransition(from: SessionState, to: SessionState) {
  if (!canSessionTransition(from, to)) throw new Error(`INVALID_SESSION_TRANSITION:${from}:${to}`);
}
