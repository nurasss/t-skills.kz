  PAYMENT_PENDING: ["PAID", "PAYMENT_FAILED", "CANCELLED", "EXPIRED"],
  PAID: ["CONSENTED", "CANCELLED", "EXPIRED"],
  ENTITLED: ["CONSENTED", "CANCELLED", "EXPIRED"],
  CONSENTED: ["ONBOARDING", "CORE_IN_PROGRESS", "CANCELLED", "INVALIDATED"],
  ONBOARDING: ["ONBOARDING", "BASE_ASSESSMENT", "CANCELLED", "INVALIDATED"],
  BASE_ASSESSMENT: ["BASE_ASSESSMENT", "BASE_SCORING", "CANCELLED", "INVALIDATED"],
  BASE_SCORING: ["CLARIFICATION", "FINAL_SCORING", "INVALIDATED"],
  CORE_IN_PROGRESS: ["CORE_IN_PROGRESS", "CORE_COMPLETE", "ADAPTIVE_SELECTING", "ADAPTIVE_IN_PROGRESS", "INVALIDATED"],
  CORE_COMPLETE: ["ADAPTIVE_GENERATING", "ADAPTIVE_SELECTING", "ADAPTIVE_IN_PROGRESS", "INVALIDATED"],
  CLARIFICATION: ["CLARIFICATION", "FINAL_SCORING", "INVALIDATED"],
  FINAL_SCORING: ["CAREER_MATCHING", "INVALIDATED"],
  CAREER_MATCHING: ["CAREER_TIEBREAK", "NARRATIVE_GENERATION", "INVALIDATED"],
