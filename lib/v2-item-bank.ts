type Core60LikertItem = {
  id: `Q${string}`;
  version: typeof V2_ITEM_BANK_VERSION;
  format: "likert";
  type: "likert";
  prompt: string;
  targetTraits: [TraitCode];
  trait: TraitCode;
  domain: string;
  reverse: boolean;
  scoring: { min: 1; max: 7; midpoint: 4; weight: 1 };
  semanticCluster: string;
};

type Core60ForcedItem = {
  id: `Q${string}`;
  version: typeof V2_ITEM_BANK_VERSION;
  format: "forced_choice";
  type: "forced_choice";
  prompt: string;
  optionA: string;
  optionB: string;
  targetTraits: [TraitCode, TraitCode];
  domain: string;
  reverse: false;
  scoring: { min: -2; max: 2; midpoint: 0; weight: 1 };
  semanticCluster: string;
};

